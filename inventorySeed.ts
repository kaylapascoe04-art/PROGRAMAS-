// Helper to construct dynamic dates relative to current date (e.g. overdue by 2 days, due in 1 day, due in 10 days)
const getIsoDateOffset = (offsetDays: number): string => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().split('T')[0];
};

